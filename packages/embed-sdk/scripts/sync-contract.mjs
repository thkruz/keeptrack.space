// Copies the engine's contract into src/contract.ts so the package ships it.
// Usage: node scripts/sync-contract.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, '../../src/embed/embed-types.ts');
const target = resolve(root, 'src/contract.ts');
const header = '// GENERATED by scripts/sync-contract.mjs from src/embed/embed-types.ts. Do not edit.\n';
const expected = header + readFileSync(source, 'utf8').replace(/\r\n/gu, '\n');

if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== expected) {
    console.error('src/contract.ts is stale. Run: node scripts/sync-contract.mjs');
    process.exit(1);
  }
  console.log('contract is up to date');
} else {
  writeFileSync(target, expected);
  console.log('contract synced');
}

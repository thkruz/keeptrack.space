/** Default retrieval date of the SODA catalog rows. */
const RETRIEVED = '2026-09-19';

/** Builds one preset: an all-sky dish with minEl from the network convention. */
const station = (p: {
  objName: string;
  uiName: string;
  lat: number;
  lon: number;
  altM: number;
  minEl: number;
  system: string;
  operator: string;
  country: string;
  sourceUrl: string;
  sourceRetrieved?: string;
}): DetailedSensorParams => ({
  objName: p.objName,
  uiName: p.uiName,
  name: p.uiName,
  system: p.system,
  operator: p.operator,
  country: p.country,
  type: SpaceObjectType.GROUND_SENSOR_STATION,
  lat: p.lat as Degrees,
  lon: p.lon as Degrees,
  alt: (p.altM / 1000) as Kilometers,
  minAz: 0 as Degrees,
  maxAz: 360 as Degrees,
  minEl: p.minEl as Degrees,
  maxEl: 90 as Degrees,
  minRng: 0 as Kilometers,
  maxRng: 50000 as Kilometers,
  zoom: p.minEl >= 10 ? ZoomValue.GEO : ZoomValue.LEO,
  sourceUrl: p.sourceUrl,
  sourceRetrieved: p.sourceRetrieved ?? RETRIEVED,
});


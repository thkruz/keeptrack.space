/**
 * branding.ts - one place for the KeepTrack logo and URL that every export, report,
 * shareable image and chart download carries (shared content is free marketing).
 *
 * - Canvases / images: {@link drawBrandUrl} and {@link drawBrandLogo} (logo + keeptrack.space).
 * - CSV: {@link appendCsvBrandFooter} adds a final `# ...` row, so header-keyed parsers
 *   (Papa with `header: true`, skipEmptyLines) still read the data rows.
 * - Plain text / TSV clipboard: {@link appendTextBrandFooter}.
 * - HTML reports: {@link brandHtmlHeader} and {@link brandHtmlFooter}.
 * - XLSX: {@link BRAND_SHEET_NAME} sheet built by {@link brandSheetRows}.
 * https://keeptrack.space
 */

export const BRAND_NAME = 'KeepTrack';
export const BRAND_URL_TEXT = 'keeptrack.space';
export const BRAND_URL = 'https://keeptrack.space';
/** Absolute logo URL for standalone HTML files that are opened away from the app. */
export const BRAND_LOGO_URL = 'https://keeptrack.space/img/logo-primary.png';
export const BRAND_SHEET_NAME = 'About KeepTrack';

const FOOTER_TEXT = `Generated by ${BRAND_NAME} - ${BRAND_URL}`;

/** Final CSV row. A single `#` cell, which comment-aware and header-keyed parsers skip. */
export const CSV_BRAND_FOOTER = `# ${FOOTER_TEXT}`;

/** Appends the brand row to CSV text (idempotent). */
export const appendCsvBrandFooter = (csv: string): string => {
  if (csv.includes(CSV_BRAND_FOOTER)) {
    return csv;
  }
  const trimmed = csv.replace(/[\r\n]+$/u, '');
  const eol = trimmed.includes('\r\n') ? '\r\n' : '\n';

  return `${trimmed}${eol}${CSV_BRAND_FOOTER}${eol}`;
};

/** Appends a plain brand line to text for the clipboard or a text file (idempotent). */
export const appendTextBrandFooter = (text: string, prefix = ''): string => {
  const line = `${prefix}${FOOTER_TEXT}`;

  if (text.includes(line)) {
    return text;
  }
  const eol = text.includes('\r\n') ? '\r\n' : '\n';

  return `${text.replace(/[\r\n]+$/u, '')}${eol}${line}${eol}`;
};

/** Rows for the extra XLSX sheet (kept off the data sheet so spreadsheet importers are not affected). */
export const brandSheetRows = (): string[][] => [[BRAND_NAME], [FOOTER_TEXT], [BRAND_URL]];

/** HTML banner for the top of a standalone report. */
export const brandHtmlHeader = (): string =>
  `<div class="kt-brand-header" style="display:flex;align-items:center;gap:10px;margin:0 0 12px;font-family:Arial,sans-serif;">` +
  `<a href="${BRAND_URL}" target="_blank" rel="noopener"><img src="${BRAND_LOGO_URL}" alt="${BRAND_NAME}" height="40" style="height:40px;"></a>` +
  `<a href="${BRAND_URL}" target="_blank" rel="noopener" style="color:#b8170d;font-weight:600;text-decoration:none;">${BRAND_URL_TEXT}</a></div>`;

/** HTML footer for the bottom of a standalone report. */
export const brandHtmlFooter = (): string =>
  `<footer class="kt-brand-footer" style="margin-top:24px;padding-top:8px;border-top:1px solid #8884;font:12px Arial,sans-serif;">` +
  `<a href="${BRAND_URL}" target="_blank" rel="noopener"><img src="${BRAND_LOGO_URL}" alt="${BRAND_NAME}" height="20" style="height:20px;vertical-align:middle;"></a> ` +
  `${FOOTER_TEXT.replace(BRAND_URL, `<a href="${BRAND_URL}" target="_blank" rel="noopener">${BRAND_URL_TEXT}</a>`)}</footer>`;

/** URL-only footer for reports whose own template already shows the logo. */
export const brandHtmlUrlFooter = (): string =>
  `<footer class="kt-brand-footer" style="margin-top:24px;padding-top:8px;border-top:1px solid #8884;font:12px Arial,sans-serif;">` +
  `${FOOTER_TEXT.replace(BRAND_URL, `<a href="${BRAND_URL}" target="_blank" rel="noopener">${BRAND_URL_TEXT}</a>`)}</footer>`;

/**
 * Brands a full HTML document string: logo header after `<body>` and logo+URL footer before `</body>`.
 * Pass `hasLogo` when the template already shows the logo, to add the URL footer only. Idempotent.
 */
export const brandHtmlDocument = (html: string, hasLogo = false): string => {
  if (html.includes('kt-brand-footer')) {
    return html;
  }
  const footer = hasLogo ? brandHtmlUrlFooter() : brandHtmlFooter();
  let out = hasLogo ? html : html.replace(/<body[^>]*>/iu, (m) => `${m}${brandHtmlHeader()}`);

  out = /<\/body>/iu.test(out) ? out.replace(/<\/body>/iu, `${footer}</body>`) : `${out}${footer}`;

  return out;
};

/**
 * Draws "keeptrack.space" in the bottom-right corner of a canvas.
 * @param scale Pixel-ratio multiplier for the font and margin (default 1; pass 2 for 2x exports).
 */
export const drawBrandUrl = (
  ctx: CanvasRenderingContext2D,
  width: number,
  height: number,
  scale = Math.max(1, width / 1200),
  position: 'bottom-right' | 'top-right' = 'bottom-right'
): void => {
  const px = Math.round(14 * scale);
  const margin = Math.round(10 * scale);

  ctx.save();
  ctx.font = `600 ${px}px "Open Sans", "Segoe UI", Arial, sans-serif`;
  ctx.textAlign = 'right';
  const top = position === 'top-right';

  ctx.textBaseline = top ? 'top' : 'bottom';
  ctx.globalAlpha = 0.9;
  ctx.lineWidth = Math.max(2, px / 5);
  ctx.strokeStyle = 'rgba(0,0,0,0.65)';
  ctx.strokeText(BRAND_URL_TEXT, width - margin, top ? margin : height - margin);
  ctx.fillStyle = '#f0f0f0';
  ctx.fillText(BRAND_URL_TEXT, width - margin, top ? margin : height - margin);
  ctx.restore();
};

/** Loads the KeepTrack logo from the app's own img folder; resolves null on failure. */
export const loadBrandLogo = (installDirectory = ''): Promise<HTMLImageElement | null> =>
  new Promise((resolve) => {
    const img = new Image();

    img.onload = () => resolve(img);
    img.onerror = () => resolve(null);
    img.src = `${installDirectory}img/logo-primary.png`;
  });

let cachedLogo_: HTMLImageElement | null = null;

/** Starts loading the logo once and caches it, so synchronous canvas exports can draw it. Safe to call repeatedly. */
export const preloadBrandLogo = (installDirectory = ''): void => {
  if (cachedLogo_ || typeof Image === 'undefined') {
    return;
  }
  void loadBrandLogo(installDirectory).then((img) => {
    cachedLogo_ = img;
  });
};

/** The cached logo, or null if {@link preloadBrandLogo} has not finished (exports then carry the URL only). */
export const getBrandLogo = (): HTMLImageElement | null => cachedLogo_;

/** Draws the logo (if loaded) in the bottom-left corner. */
export const drawBrandLogo = (ctx: CanvasRenderingContext2D, width: number, height: number, logo: HTMLImageElement | null = cachedLogo_): void => {
  if (!logo || logo.naturalWidth === 0) {
    return;
  }
  const scale = Math.max(1, width / 1200);
  const h = Math.round(36 * scale);
  const w = Math.round(logo.naturalWidth * (h / logo.naturalHeight));
  const m = Math.round(10 * scale);

  ctx.save();
  ctx.globalAlpha = 0.9;
  ctx.drawImage(logo, m, height - h - m, w, h);
  ctx.restore();
};

/** Logo bottom-left plus URL bottom-right, for chart/image exports that have neither. */
export const drawBrandMark = (ctx: CanvasRenderingContext2D, width: number, height: number, logo: HTMLImageElement | null = cachedLogo_): void => {
  drawBrandLogo(ctx, width, height, logo);
  drawBrandUrl(ctx, width, height);
};

/**
 * Returns a PNG data URL of `source` with the KeepTrack logo and URL drawn on a copy
 * (the source canvas is not modified). Synchronous; the logo is included only once
 * {@link preloadBrandLogo} has finished, the URL is always included.
 */
export const brandedCanvasDataUrl = (source: HTMLCanvasElement, type = 'image/png'): string => {
  const out = document.createElement('canvas');

  out.width = source.width;
  out.height = source.height;
  const ctx = out.getContext('2d');

  if (!ctx) {
    return source.toDataURL(type);
  }
  ctx.drawImage(source, 0, 0);
  drawBrandMark(ctx, out.width, out.height);

  return out.toDataURL(type);
};

/** Async variant for an image data URL (for example `echarts.getDataURL()`): loads it, brands it, returns a PNG data URL. */
export const brandImageDataUrl = async (dataUrl: string, installDirectory = ''): Promise<string> => {
  const [img, logo] = await Promise.all([
    new Promise<HTMLImageElement | null>((resolve) => {
      const i = new Image();

      i.onload = () => resolve(i);
      i.onerror = () => resolve(null);
      i.src = dataUrl;
    }),
    cachedLogo_ ? Promise.resolve(cachedLogo_) : loadBrandLogo(installDirectory),
  ]);

  if (!img) {
    return dataUrl;
  }
  const out = document.createElement('canvas');

  out.width = img.width;
  out.height = img.height;
  const ctx = out.getContext('2d');

  if (!ctx) {
    return dataUrl;
  }
  ctx.drawImage(img, 0, 0);
  drawBrandMark(ctx, out.width, out.height, logo);

  return out.toDataURL('image/png');
};
